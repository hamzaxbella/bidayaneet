export function programVisual(name: string) {
  const value = name.toLowerCase();
  if (value.includes("ormva")) return { src: "/editorial/action-reflection.webp", alt: "Planning a rural career pathway in Souss-Massa", position: "50% 44%" };
  if (value.includes("ada") || value.includes("agri")) return { src: "/editorial/program-agriculture-v2.png", alt: "Young people learning greenhouse cultivation with a local mentor", position: value.includes("ada") ? "35% 52%" : "65% 48%" };
  if (value.includes("ofppt") || value.includes("vocational")) return { src: "/editorial/program-vocational-v2.png", alt: "Vocational learners practicing engine maintenance in a workshop", position: "50% 44%" };
  if (value.includes("ministry of tourism")) return { src: "/editorial/program-cooperative-v2.png", alt: "Young people learning basket weaving in a local craft cooperative", position: "55% 48%" };
  if (value.includes("hospitality")) return { src: "/editorial/program-hospitality-v2.png", alt: "A learner practicing hotel reception with an experienced colleague", position: "48% 42%" };
  if (value.includes("onmt") || value.includes("tourism")) return { src: "/editorial/mountain-progress.webp", alt: "Exploring mountain visitor routes in Morocco", position: "50% 45%" };
  if (value.includes("anapec")) return { src: "/editorial/action-interview.webp", alt: "A career guidance conversation with a young person", position: "50% 40%" };
  if (value.includes("local internship")) return { src: "/editorial/opp-marketing.webp", alt: "A team collaborating on a practical business project", position: "50% 45%" };
  if (value.includes("economic") || value.includes("enterprise")) return { src: "/editorial/opp-entrepreneur.webp", alt: "Preparing a small business project", position: "50% 42%" };
  if (value.includes("micro")) return { src: "/editorial/action-cv.webp", alt: "Preparing a CV during a practical workshop", position: "50% 48%" };
  if (value.includes("youth")) return { src: "/editorial/action-digital.webp", alt: "Young people discovering digital skills together", position: "50% 40%" };
  if (value.includes("indh")) return { src: "/editorial/mediator-field.webp", alt: "Young people joining a local community pathway", position: "50% 48%" };
  return { src: "/editorial/partner-training.webp", alt: "A practical learning session for local youth", position: "50% 45%" };
}
export function programImage(name: string) { return programVisual(name).src; }
export function normalizeAdminSearch(value: string) { return value.trim().normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase(); }
